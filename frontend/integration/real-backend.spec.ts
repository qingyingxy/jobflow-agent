import { expect, test } from "@playwright/test";

const api = "http://127.0.0.1:18021";
const headers = { "X-User-ID": "local-user" };

test("homepage filters without analysis, keeps unknown cohorts and supports optional matching", async ({ page, request }, testInfo) => {
  await request.put(`${api}/api/profile`, { headers, data: { graduation_year: 2027, degree: "硕士", major: "计算机" } });
  await request.post(`${api}/api/evidence`, { headers, data: { type: "project", title: "服务项目", claim: "使用 Python 开发服务并完成接口测试。", skills: ["Python"], source: "synthetic_e2e" } });
  await page.goto("/");
  await page.getByRole("textbox", { name: "你想找什么" }).fill("2027届上海 Python 后端校招，不考虑北京");
  const started = page.waitForResponse(r => /\/discovery\/goals\/[^/]+\/search$/.test(r.url()) && r.request().method() === "POST");
  await page.getByRole("button", { name: "搜索并筛选" }).click();
  const runId = (await (await started).json()).id;
  await expect.poll(async () => {
    const r = await request.get(`${api}/api/discovery/runs/${runId}`, { headers });
    return (await r.json()).status;
  }, { timeout: 30_000 }).not.toBe("RUNNING");
  const run = await (await request.get(`${api}/api/discovery/runs/${runId}`, { headers })).json();
  expect(run.result_matches).toHaveLength(2);
  expect(run.analysis_target_count, JSON.stringify(run.result_matches)).toBe(0);
  expect(run.analysis_completed_count, run.failure_summary).toBe(0);
  expect(run.analysis_status).toBe("NOT_REQUESTED");
  const excluded = run.result_matches.find((m: { mismatch_reasons: string[] }) => m.mismatch_reasons.includes("excluded_location"));
  expect(excluded).toBeTruthy();
  const accepted = run.result_matches.find((m: { filter_status: string }) => m.filter_status === "pending");
  expect(accepted.checks.some((check: { field: string; status: string }) => check.field === "graduation_year" && check.status === "pending")).toBeTruthy();
  expect((await request.get(`${api}/api/jobs/${accepted.job_posting_id}/analysis`, { headers })).status()).toBe(404);
  await page.reload();
  await expect(page.getByRole("textbox", { name: "你想找什么" })).toHaveValue("2027届上海 Python 后端校招，不考虑北京");
  await expect(page.getByRole("button", { name: "Python 开发工程师（上海）", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Python 开发工程师（北京）", exact: true })).toHaveCount(0);
  await page.getByRole("checkbox", { name: "显示明确不符或已关闭的岗位" }).check();
  await page.getByRole("button", { name: "展开链路验收公司（明确不符）", exact: true }).click();
  await expect(page.getByRole("button", { name: "Python 开发工程师（北京）", exact: true })).toBeVisible();
  await page.getByRole("checkbox", { name: "显示明确不符或已关闭的岗位" }).uncheck();
  const row = page.getByRole("row").filter({ has: page.getByRole("button", { name: "Python 开发工程师（上海）", exact: true }) });
  await row.getByRole("button", { name: "保存", exact: true }).click();
  await expect(row.getByRole("cell", { name: "已保存", exact: true })).toBeVisible();
  const imports: string[] = [];
  page.on("request", (r) => { if (r.url().endsWith("/jobs/import-text")) imports.push(r.url()); });
  await page.getByRole("button", { name: "Python 开发工程师（上海）", exact: true }).click();
  await page.getByRole("button", { name: "分析匹配" }).click();
  const analyzed = page.waitForResponse(r => r.url().endsWith(`/jobs/${accepted.job_posting_id}/analyze`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "开始匹配", exact: true }).first().click();
  const before = await (await analyzed).json();
  expect(before.matches[0].support_level).toBe("supported");
  const reanalyzed = page.waitForResponse(r => r.url().endsWith(`/jobs/${accepted.job_posting_id}/analyze`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "重新分析", exact: true }).click();
  const repeated = await (await reanalyzed).json();
  expect(imports).toEqual([]);
  expect(repeated.job.id).toBe(accepted.job_posting_id);
  expect(repeated.job.source_url).toBe(before.job.source_url);
  expect(repeated.job.source_url).toBeTruthy();
  expect(repeated.analysis_id).toBe(before.analysis_id);
  const stored = await (await request.get(`${api}/api/jobs/${accepted.job_posting_id}/analysis`, { headers })).json();
  expect(stored.analysis_id).toBe(repeated.analysis_id);
  await page.getByRole("button", { name: "纠正岗位条件", exact: true }).click();
  await expect(page.getByLabel("条件1原文")).toBeVisible();
  await page.getByLabel("条件1强度").selectOption("preferred");
  await page.getByLabel("纠错原因").fill("核对原文后改为优先条件");
  const correctionResponse = page.waitForResponse(r => r.url().endsWith("/corrections") && r.request().method() === "PUT");
  await page.getByRole("button", { name: "保存并重新匹配", exact: true }).click();
  const corrected = await (await correctionResponse).json();
  expect(corrected.agent_run_ids).toEqual([]);
  expect(corrected.structured_jd.requirements[0].mandatory).toBe(false);
  await page.getByRole("button", { name: "纠正岗位条件", exact: true }).click();
  await expect(page.getByText("修改记录（1）", { exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("correction-editor.png"), fullPage: true, animations: "disabled" });
  const restoreResponse = page.waitForResponse(r => r.url().endsWith("/corrections") && r.request().method() === "PUT");
  await page.getByRole("button", { name: "恢复模型结果", exact: true }).click();
  expect((await (await restoreResponse).json()).structured_jd.requirements).toEqual(before.structured_jd.requirements);
  const candidates = await (await request.get(`${api}/api/candidates`, { headers })).json();
  const candidate = candidates.find((c: { job_posting_id: string }) => c.job_posting_id === accepted.job_posting_id);
  const application = await (await request.post(`${api}/api/candidates/${candidate.id}/prepare-application`, { headers })).json();
  await page.getByRole("button", { name: /申请进度/ }).click();
  await page.getByText("已经在官网投递？记录一下", { exact: true }).click();
  await expect(page.getByRole("button", { name: "记录为已投递", exact: true })).toBeDisabled();
  await page.getByLabel("我确认已经在官网提交了这份申请").check();
  await page.getByRole("button", { name: "记录为已投递", exact: true }).click();
  await expect(page.getByText("用户确认投递", { exact: true })).toBeVisible();
  expect((await (await request.get(`${api}/api/applications/${application.id}`, { headers })).json()).submission_source).toBe("user_confirmed");
  await expect(page.getByText("用户登记已投递", { exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("manual-submission.png"), fullPage: true, animations: "disabled" });
  await page.reload();
  await page.getByLabel("定期更新", { exact: true }).selectOption("30");
  await expect(page.getByLabel("定期更新", { exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByLabel("定期更新", { exact: true })).toHaveValue("30");
  await page.getByLabel("定期更新", { exact: true }).selectOption("0");
  await page.getByRole("combobox", { name: "岗位范围", exact: true }).selectOption("all");
  await expect(page.getByRole("button", { name: "Python 开发工程师（上海）", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("search-analysis-saved.png"), fullPage: true, animations: "disabled" });
});

test("real API persists discovery, cohort evidence, any_of and saved candidate", async ({ page, request }, testInfo) => {
  const profile = await request.put(`${api}/api/profile`, { headers, data: { graduation_year: 2026, degree: "硕士", major: "计算机", search_preferences: { preferred_locations: ["上海"], job_types: ["internship"] } } });
  expect(profile.ok()).toBeTruthy();
  const evidence = await request.post(`${api}/api/evidence`, { headers, data: { type: "project", title: "Python 项目", claim: "使用 Python 开发服务", skills: ["Python"], source: "e2e_fixture" } });
  expect(evidence.ok()).toBeTruthy();
  const discover = () => request.post(`${api}/api/discovery/runs`, { headers, data: { source_url: "https://boards.greenhouse.io/jobflowfixture", company: "验收公司" } });
  const first = await discover();
  expect(first.ok()).toBeTruthy();
  expect((await first.json()).new_count).toBe(1);
  const repeat = await discover();
  expect(repeat.ok()).toBeTruthy();
  expect((await repeat.json()).duplicate_count).toBe(1);

  await page.goto("/");
  await page.getByRole("combobox", { name: "岗位范围", exact: true }).selectOption("all");
  await page.getByRole("checkbox", { name: "显示明确不符或已关闭的岗位" }).check();
  await page.getByRole("button", { name: "全部展开", exact: true }).click();
  await page.getByRole("button", { name: "Python 开发工程师", exact: true }).click();
  const analysisResponse = page.waitForResponse(r => r.url().endsWith("/analyze") && r.request().method() === "POST");
  await page.getByRole("button", { name: "分析匹配" }).click();
  await page.getByRole("button", { name: "开始匹配", exact: true }).first().click();
  const response = await analysisResponse;
  expect(response.ok()).toBeTruthy();
  const body = await response.json();
  expect(body.structured_jd.graduation_condition_kind).toBe("qualified");
  expect(body.eligibility.eligible).toBe("unknown");
  expect(body.matches[0].requirement.relation).toBe("any_of");
  expect(body.matches[0].support_level).toBe("supported");
  await expect(page.locator(".eligibility-section").getByText("岗位届别含附加条件或语义不明确，不能仅凭毕业年份确认符合资格")).toBeVisible();
  await expect(page.getByText("岗位原文：2027届中国大陆毕业生，2026届海外毕业生")).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("cohort-analysis.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "返回岗位列表" }).click();
  await page.getByRole("combobox", { name: "岗位范围", exact: true }).selectOption("all");
  const row = page.getByRole("row").filter({ has: page.getByRole("button", { name: "Python 开发工程师", exact: true }) });
  await page.getByRole("checkbox", { name: "显示明确不符或已关闭的岗位" }).check();
  await page.getByRole("button", { name: "全部展开", exact: true }).click();
  await row.getByRole("button", { name: "保存", exact: true }).click();
  await expect(row.getByRole("cell", { name: "已保存", exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("combobox", { name: "岗位范围", exact: true }).selectOption("saved");
  await expect(page.getByRole("button", { name: "Python 开发工程师", exact: true })).toBeVisible();
  const persisted = await request.get(`${api}/api/jobs/${body.job.id}/analysis`, { headers });
  expect((await persisted.json()).structured_jd).toEqual(body.structured_jd);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("saved-candidate.png"), fullPage: true, animations: "disabled" });
});
